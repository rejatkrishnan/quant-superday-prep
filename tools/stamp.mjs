// Cache-busting without a build step.
// Writes an import map into index.html that maps every JS module to "<path>?v=<content hash>",
// and stamps the CSS/entry-script URLs. Changing any file changes its URL, so browsers can never
// mix a stale cached module with fresh ones (GitHub Pages caches files for 10 minutes).
//   node tools/stamp.mjs          rewrite index.html
//   node tools/stamp.mjs --check  exit 1 if index.html is out of date (used by tests)
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const hash = (f) => createHash('sha256').update(readFileSync(join(root, f))).digest('hex').slice(0, 10);
const walk = (d) => readdirSync(join(root, d)).flatMap((n) => {
  const p = join(d, n);
  return statSync(join(root, p)).isDirectory() ? walk(p) : p.endsWith('.js') ? [p] : [];
});

const files = walk('js').map((f) => relative(root, join(root, f)).split('\\').join('/')).sort();
const imports = Object.fromEntries(files.map((f) => [`./${f}`, `./${f}?v=${hash(f)}`]));
const block = [
  '<!-- stamp:start (generated by tools/stamp.mjs — do not edit) -->',
  `  <link rel="stylesheet" href="css/style.css?v=${hash('css/style.css')}">`,
  `  <script type="importmap">${JSON.stringify({ imports }, null, 2).replace(/\n/g, '\n  ')}</script>`,
  `  <script type="module" src="js/main.js?v=${hash('js/main.js')}"></script>`,
  '  <!-- stamp:end -->',
].join('\n');

const htmlPath = join(root, 'index.html');
const html = readFileSync(htmlPath, 'utf8');
const re = /<!-- stamp:start[\s\S]*?<!-- stamp:end -->/;
if (!re.test(html)) throw new Error('index.html is missing the <!-- stamp:start --> … <!-- stamp:end --> markers');
const next = html.replace(re, block);
if (process.argv.includes('--check')) {
  if (next !== html) { console.error('index.html is out of date: run `node tools/stamp.mjs`'); process.exit(1); }
  console.log(`stamp ok (${files.length} modules)`);
} else {
  writeFileSync(htmlPath, next);
  console.log(`stamped ${files.length} modules`);
}
